#!/usr/bin/env bash
# HomeCore OS — nftables firewall.
#
#   firewall.sh render            print the ruleset generated from /etc/homecore/homecore.env
#   firewall.sh apply [--safe]    write /etc/homecore/firewall.nft and load it
#                                 --safe: roll back after 120 s unless you confirm
#   firewall.sh status            show the loaded table
#   firewall.sh detect            print detected LAN prefixes
#   firewall.sh disable           unload the table (everything open — for debugging only)
#
# Policy: drop all inbound traffic except loopback, replies, essential ICMP,
# DHCP replies, Tailscale, and the service ports listed in homecore.env —
# which are only reachable from the LAN prefixes and the tailscale0 interface.
# SSH is rate-limited per source address (light alternative to fail2ban).
set -Eeuo pipefail
# shellcheck source=scripts/lib.sh
. "$(dirname "$(readlink -f "$0")")/lib.sh"

RULES="$HC_ETC/firewall.nft"

detect_lan4() {
  ip -o -4 route show proto kernel scope link 2>/dev/null |
    awk '$2 == "dev" && $3 !~ /^(lo|docker|br-|veth|tailscale|virbr)/ && $1 ~ /\// { print $1 }' | sort -u
}

detect_lan6() {
  ip -o -6 route show proto kernel 2>/dev/null |
    awk '$2 == "dev" && $3 !~ /^(lo|docker|br-|veth|tailscale|virbr)/ && $1 ~ /\// && $1 !~ /^fe80/ { print $1 }' | sort -u
}

# Join words with ", " for an nft set/element list.
# shellcheck disable=SC2048,SC2086
join_csv() { local IFS=' '; set -- $*; local out=""; for x in "$@"; do out+="${out:+, }$x"; done; printf '%s' "$out"; }

render() {
  load_env
  local lan4=${LAN4:-$(detect_lan4 | xargs)}
  local lan6="fe80::/10 ${LAN6:-$(detect_lan6 | xargs)}"
  local tcp udp ts_tcp admin4 admin6
  tcp=$(join_csv "${LAN_TCP_PORTS:-22 8123 1883 8080}")
  udp=$(join_csv "${LAN_UDP_PORTS:-5353}")
  ts_tcp=$(join_csv "${TS_TCP_PORTS:-22 8123 1883 8080}")
  admin4=$(join_csv "${ADMIN4:-}")
  admin6=$(join_csv "${ADMIN6:-}")
  local ssh_rate=${SSH_RATE:-8/minute}

  [[ -n "$lan4" ]] || warn "No IPv4 LAN prefix detected — set LAN4 in $HC_ENV"

  cat <<EOF
#!/usr/sbin/nft -f
# HomeCore OS firewall — GENERATED by scripts/firewall.sh on $(date -Is).
# Do not edit: change $HC_ENV and run: sudo homecore firewall apply

table inet homecore
delete table inet homecore

table inet homecore {
  set lan4 {
    type ipv4_addr; flags interval; auto-merge;
$( [[ -n "$lan4" ]] && echo "    elements = { $(join_csv "$lan4") }" )
  }
  set lan6 {
    type ipv6_addr; flags interval; auto-merge;
    elements = { $(join_csv "$lan6") }
  }
  set admin4 {
    type ipv4_addr; flags interval; auto-merge;
$( [[ -n "$admin4" ]] && echo "    elements = { $admin4 }" )
  }
  set admin6 {
    type ipv6_addr; flags interval; auto-merge;
$( [[ -n "$admin6" ]] && echo "    elements = { $admin6 }" )
  }
  set ssh_meter4 { type ipv4_addr; size 4096; flags dynamic, timeout; timeout 5m; }
  set ssh_meter6 { type ipv6_addr; size 4096; flags dynamic, timeout; timeout 5m; }

  chain input {
    type filter hook input priority filter; policy drop;

    iif "lo" accept
    ct state established,related accept
    ct state invalid drop

    # ICMP / ICMPv6 needed for a healthy network (IPv6 breaks without ND)
    ip protocol icmp icmp type { destination-unreachable, time-exceeded, parameter-problem } accept
    ip protocol icmp icmp type echo-request limit rate 5/second accept
    ip6 nexthdr icmpv6 icmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem, nd-router-advert, nd-neighbor-solicit, nd-neighbor-advert, mld-listener-query } accept
    ip6 nexthdr icmpv6 icmpv6 type echo-request limit rate 5/second accept

    # DHCP replies
    udp sport 67 udp dport 68 accept
    udp sport 547 udp dport 546 accept

    # Tailscale: WireGuard transport + everything arriving through the tunnel
    udp dport ${TAILSCALE_UDP_PORT:-41641} accept
    iifname "tailscale0" jump from_tailnet

    # Administrator workstations (SSH always allowed, still rate-limited)
    ip saddr @admin4 tcp dport 22 jump ssh_guard
    ip6 saddr @admin6 tcp dport 22 jump ssh_guard

    # Local network
    ip saddr @lan4 jump from_lan
    ip6 saddr @lan6 jump from_lan

    limit rate 6/minute burst 10 packets log prefix "homecore-drop: " level info
  }

  chain ssh_guard {
    ct state new meta nfproto ipv4 update @ssh_meter4 { ip saddr limit rate over ${ssh_rate} burst 4 packets } log prefix "homecore-ssh-flood: " level warn drop
    ct state new meta nfproto ipv6 update @ssh_meter6 { ip6 saddr limit rate over ${ssh_rate} burst 4 packets } log prefix "homecore-ssh-flood: " level warn drop
    accept
  }

  chain from_lan {
    tcp dport 22 jump ssh_guard
$( [[ -n "$tcp" ]] && echo "    tcp dport { $tcp } accept" )
$( [[ -n "$udp" ]] && echo "    udp dport { $udp } accept" )
  }

  chain from_tailnet {
    tcp dport 22 jump ssh_guard
$( [[ -n "$ts_tcp" ]] && echo "    tcp dport { $ts_tcp } accept" )
  }

  # HomeCore does not route: no Docker NAT, no subnet router. Drop forwarded traffic.
  chain forward {
    type filter hook forward priority filter; policy drop;
  }

  chain output {
    type filter hook output priority filter; policy accept;
  }
}
EOF
}

apply() {
  install -d -m 0755 "$HC_ETC"
  local tmp backup=""
  tmp=$(mktemp)
  render >"$tmp"
  nft -c -f "$tmp" || { rm -f "$tmp"; die "Generated ruleset failed validation — nothing changed."; }
  if [[ -f "$RULES" ]]; then backup="$RULES.prev"; cp -f "$RULES" "$backup"; fi
  install -m 0600 "$tmp" "$RULES"
  rm -f "$tmp"
  nft -f "$RULES"
  ok "Firewall loaded ($RULES)."

  if [[ "${1:-}" == "--safe" && -t 0 ]]; then
    warn "Open a NEW SSH session to this machine now to make sure you can still log in."
    local answer=""
    read -r -t 120 -p "Type 'keep' within 120 s to keep the new rules: " answer || true
    if [[ "$answer" != "keep" ]]; then
      if [[ -n "$backup" ]]; then
        cp -f "$backup" "$RULES"; nft -f "$RULES"; warn "Rolled back to the previous ruleset."
      else
        nft delete table inet homecore; warn "Rolled back: firewall table removed."
      fi
      exit 1
    fi
    ok "Rules kept."
  fi
}

case "${1:-}" in
  render) render ;;
  apply) require_root "$@"; shift; apply "$@" ;;
  status) require_root "$@"; nft list table inet homecore ;;
  detect) echo "IPv4: $(detect_lan4 | xargs)"; echo "IPv6: $(detect_lan6 | xargs)" ;;
  disable) require_root "$@"; nft delete table inet homecore && warn "Firewall disabled until next boot/apply." ;;
  *) sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
