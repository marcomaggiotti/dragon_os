#!/usr/bin/env bash
# HomeCore OS — MQTT accounts with least-privilege roles.
#
#   mqtt-user.sh add <user> <role> [--print]   create/rotate a user (random password)
#   mqtt-user.sh remove <user>
#   mqtt-user.sh list
#   mqtt-user.sh acl                            regenerate the ACL file from the roles file
#   mqtt-user.sh bootstrap                      create the built-in service accounts
#
# Roles
#   admin    read/write everything            (Home Assistant)
#   zigbee   zigbee2mqtt/# + discovery         (Zigbee2MQTT)
#   device   <user>/# + its own discovery      (ESPHome/DIY: MQTT user = node name)
#   cli      read everything, write only zigbee2mqtt/bridge/request/#  (homecore CLI)
#   readonly read everything                   (dashboards, debugging)
#
# Passwords of service accounts are kept in /opt/homecore/secrets/mqtt/<user>.pass (0600).
# Device passwords are printed once and not stored.
set -Eeuo pipefail
# shellcheck source=scripts/lib.sh
. "$(dirname "$(readlink -f "$0")")/lib.sh"
require_root "$@"

CONF_DIR="$HC_ROOT/config/mosquitto"
PASSWD="$CONF_DIR/passwd"
ACL="$CONF_DIR/acl"
ROLES="$CONF_DIR/roles"
PASS_DIR="$HC_SECRETS/mqtt"
CLI_DIR="$HC_SECRETS/cli"
ROLES_VALID="admin zigbee device cli readonly"

load_env
MOSQ_IMAGE="eclipse-mosquitto:$(get_kv "$HC_ROOT/.env" MOSQUITTO_VERSION)"
[[ "$MOSQ_IMAGE" == *: ]] && MOSQ_IMAGE="eclipse-mosquitto:2"

validate_user() {
  # Strict charset: usernames end up in the ACL file and in topic names, so no
  # whitespace, newlines, '#', '+', '/' or '%' (prevents ACL/topic injection).
  [[ "$1" =~ ^[a-z0-9][a-z0-9_-]{1,31}$ ]] ||
    die "Invalid user '$1': use 2-32 chars of a-z 0-9 _ - (start with a letter/digit)."
}

ensure_files() {
  install -d -m 0750 -o "$MOSQ_UID" -g "$MOSQ_UID" "$CONF_DIR"
  install -d -m 0700 "$HC_SECRETS" "$PASS_DIR"
  install -d -m 0700 -o "$MOSQ_UID" -g "$MOSQ_UID" "$CLI_DIR"
  for f in "$PASSWD" "$ACL" "$ROLES"; do
    [[ -f "$f" ]] || : >"$f"
    chown "$MOSQ_UID:$MOSQ_UID" "$f"
    chmod 0600 "$f"
  done
}

mosq_passwd() {
  docker run --rm --network none --user "$MOSQ_UID:$MOSQ_UID" \
    -v "$CONF_DIR:/mosquitto/config" "$MOSQ_IMAGE" mosquitto_passwd "$@" >/dev/null
}

role_of() { awk -F: -v u="$1" '$1 == u { print $2; exit }' "$ROLES"; }

gen_acl() {
  local tmp user role
  tmp=$(mktemp)
  {
    echo "# Generated by scripts/mqtt-user.sh from 'roles' — do not edit by hand."
    echo "# Anything not listed here is denied."
    while IFS=: read -r user role; do
      [[ -z "$user" || "$user" == \#* ]] && continue
      validate_user "$user"
      echo
      echo "user $user"
      case "$role" in
        admin)    echo "topic readwrite #" ;;
        readonly) echo "topic read #" ;;
        cli)      echo "topic read #"
                  echo "topic write zigbee2mqtt/bridge/request/#" ;;
        zigbee)   echo "topic readwrite zigbee2mqtt/#"
                  echo "topic readwrite homeassistant/#" ;;
        device)   echo "topic readwrite $user/#"
                  echo "topic write homeassistant/+/$user/#"
                  echo "topic read homeassistant/status" ;;
        *) die "Unknown role '$role' for user '$user' in $ROLES" ;;
      esac
    done <"$ROLES"
  } >"$tmp"
  cat "$tmp" >"$ACL"
  rm -f "$tmp"
  chown "$MOSQ_UID:$MOSQ_UID" "$ACL"
  chmod 0600 "$ACL"
}

reload_broker() {
  if container_running homecore-mosquitto; then
    docker kill --signal=HUP homecore-mosquitto >/dev/null && ok "Broker reloaded users and ACL."
  fi
}

write_service_secret() {
  local user=$1 role=$2 pass=$3
  umask 077
  printf '%s\n' "$pass" >"$PASS_DIR/$user.pass"
  case "$role" in
    zigbee)
      local token
      token=$(get_kv "$HC_SECRETS/zigbee2mqtt.env" ZIGBEE2MQTT_CONFIG_FRONTEND_AUTH_TOKEN)
      [[ -n "$token" ]] || token=$(gen_secret 32)
      cat >"$HC_SECRETS/zigbee2mqtt.env" <<EOF
ZIGBEE2MQTT_CONFIG_MQTT_USER=$user
ZIGBEE2MQTT_CONFIG_MQTT_PASSWORD=$pass
ZIGBEE2MQTT_CONFIG_FRONTEND_AUTH_TOKEN=$token
EOF
      chmod 0600 "$HC_SECRETS/zigbee2mqtt.env" ;;
    cli)
      # Options files read by mosquitto_sub/mosquitto_pub inside the broker
      # container (XDG_CONFIG_HOME=/cli), so the password never shows up in `ps`.
      for tool in mosquitto_sub mosquitto_pub; do
        printf -- '-h 127.0.0.1\n-u %s\n-P %s\n' "$user" "$pass" >"$CLI_DIR/$tool"
        chown "$MOSQ_UID:$MOSQ_UID" "$CLI_DIR/$tool"
        chmod 0400 "$CLI_DIR/$tool"
      done ;;
  esac
}

cmd_add() {
  local user=${1:-} role=${2:-} print=${3:-}
  [[ -n "$user" && -n "$role" ]] || die "Usage: mqtt-user.sh add <user> <role>   roles: $ROLES_VALID"
  validate_user "$user"
  [[ " $ROLES_VALID " == *" $role "* ]] || die "Unknown role '$role'. Roles: $ROLES_VALID"
  ensure_files
  local pass
  pass=$(gen_secret 32)
  mosq_passwd -b /mosquitto/config/passwd "$user" "$pass"
  chmod 0600 "$PASSWD"
  local tmp
  tmp=$(mktemp)
  awk -F: -v u="$user" '$1 != u' "$ROLES" >"$tmp"
  echo "$user:$role" >>"$tmp"
  cat "$tmp" >"$ROLES"
  rm -f "$tmp"
  gen_acl
  case "$role" in
    device)
      echo
      echo "  MQTT user:     $user"
      echo "  MQTT password: $pass"
      echo "  (shown once — store it in your ESPHome secrets.yaml; topic prefix must be '$user')"
      echo ;;
    *)
      write_service_secret "$user" "$role" "$pass"
      ok "User '$user' ($role) — password saved to $PASS_DIR/$user.pass"
      if [[ "$print" == "--print" ]]; then echo "  MQTT password: $pass"; fi ;;
  esac
  reload_broker
}

cmd_remove() {
  local user=${1:-}
  validate_user "$user"
  ensure_files
  [[ -n "$(role_of "$user")" ]] || die "No such MQTT user: $user"
  mosq_passwd -D /mosquitto/config/passwd "$user" || true
  local tmp
  tmp=$(mktemp)
  awk -F: -v u="$user" '$1 != u' "$ROLES" >"$tmp"
  cat "$tmp" >"$ROLES"
  rm -f "$tmp" "$PASS_DIR/$user.pass"
  gen_acl
  ok "Removed MQTT user '$user'."
  reload_broker
}

cmd_list() {
  ensure_files
  printf '%-24s %s\n' USER ROLE
  awk -F: 'NF == 2 && $1 !~ /^#/ { printf "%-24s %s\n", $1, $2 }' "$ROLES"
}

cmd_bootstrap() {
  ensure_files
  [[ -n "$(role_of homeassistant)" ]] || cmd_add homeassistant admin
  [[ -n "$(role_of hc-cli)" ]] || cmd_add hc-cli cli
}

case "${1:-}" in
  add) shift; cmd_add "$@" ;;
  remove|rm|del) shift; cmd_remove "$@" ;;
  list|ls) cmd_list ;;
  acl) ensure_files; gen_acl; reload_broker ;;
  bootstrap) cmd_bootstrap ;;
  *) sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
